export type MarketCandle = {
  open: number;
  high: number;
  low: number;
  close: number;
};

export type MarketOverviewItem = {
  id: string;
  title: string;
  value: string;
  change: string;
  changeRate: string;
  direction: "up" | "down";
  ticks: string[];
  candles: MarketCandle[];
};

const createCandles = (closes: number[], spread: number): MarketCandle[] =>
  closes.map((close, index) => {
    const previousClose = index === 0 ? close * 0.997 : closes[index - 1];
    const open = previousClose + ((index % 5) - 2) * spread * 0.12;
    const wick = spread * (0.5 + (index % 4) * 0.13);

    return {
      open,
      high: Math.max(open, close) + wick,
      low: Math.min(open, close) - wick * 0.82,
      close,
    };
  });

